#!/usr/bin/env python3
"""Live end-to-end verification for 1.0.17 (login + new icon).

Runs the real server (app/app.py) and drives it with curl, checking
every 1.0.17 behaviour:

  A. Login wall: unauthenticated / and /progress redirect to /login,
     /api/status answers 401; the login page renders.
  B. Default admin/admin logs in; the settings page shows the
     change-password card and a logout button.
  C. Change password: wrong current / mismatch / too short are
     rejected; a good change works, the old password stops working
     and the new one logs in.
  D. Logout: the session is destroyed and / redirects to /login.
  E. /sub/<name> stays public without a login (proxy clients fetch
     it on their own and cannot log in).
  F. Icons: the four icon files are RGBA PNGs at the right sizes and
     match the new globe+bolt design (regenerated by make_icons.py).

Usage: python3 tests/verify_1_0_17.py
Exit code 0 means every check passed.
"""

import json
import os
import struct
import subprocess
import sys
import tempfile
import time
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.join(ROOT, "app", "app.py")
PORT = 18092
BASE = "http://127.0.0.1:%d" % PORT

PASSES = []
FAILURES = []
COOKIE_JAR = None


def check(name, cond, detail=""):
    if cond:
        PASSES.append(name)
        print("PASS: %s" % name, flush=True)
    else:
        FAILURES.append(name)
        print("FAIL: %s %s" % (name, detail), flush=True)


def curl(method, path, fields=None, jar=True, follow=True):
    cmd = ["curl", "-s", "--noproxy", "*", "-m", "30"]
    if follow:
        cmd.append("-L")
    if jar and COOKIE_JAR:
        cmd += ["-c", COOKIE_JAR, "-b", COOKIE_JAR]
    if method == "POST":
        if fields:
            for key, value in fields.items():
                cmd += ["--data-urlencode", "%s=%s" % (key, value)]
        else:
            cmd += ["-d", ""]
    cmd.append(BASE + path)
    out = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    return out.stdout


def curl_status(method, path, fields=None, jar=True):
    """Like curl() but returns the HTTP status code (no redirect)."""
    cmd = ["curl", "-s", "-o", "/dev/null", "-w", "%{http_code}",
           "--noproxy", "*", "-m", "30"]
    if jar and COOKIE_JAR:
        cmd += ["-c", COOKIE_JAR, "-b", COOKIE_JAR]
    if method == "POST":
        if fields:
            for key, value in fields.items():
                cmd += ["--data-urlencode", "%s=%s" % (key, value)]
        else:
            cmd += ["-d", ""]
    cmd.append(BASE + path)
    out = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    try:
        return int(out.stdout.strip())
    except ValueError:
        return -1


class Server:
    def __init__(self, data_dir):
        self.data_dir = data_dir
        env = dict(os.environ)
        env["CFBESTIPD_DATA_DIR"] = data_dir
        env["CFBESTIPD_PORT"] = str(PORT)
        log = open(os.path.join(data_dir, "server.log"), "ab")
        self.proc = subprocess.Popen(
            [sys.executable, APP], env=env, stdout=log,
            stderr=subprocess.STDOUT)
        self.log = log

    def wait_ready(self, timeout=90):
        deadline = time.time() + timeout
        while time.time() < deadline:
            try:
                if "CF优选IP" in curl("GET", "/login", jar=False):
                    return True
            except Exception:
                pass
            time.sleep(2)
        return False

    def stop(self):
        self.proc.terminate()
        try:
            self.proc.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self.proc.kill()
        self.log.close()


def png_info(path):
    """Return (width, height, color_type) of a PNG, or None."""
    with open(path, "rb") as fh:
        data = fh.read(33)
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    width, height = struct.unpack(">II", data[16:24])
    return width, height, data[25]


def main():
    global COOKIE_JAR
    work = tempfile.mkdtemp(prefix="cfbestipd-verify-1017-")
    COOKIE_JAR = os.path.join(work, "cookies.txt")
    data = os.path.join(work, "data")
    os.makedirs(data)
    srv = Server(data)
    try:
        check("A0 server starts", srv.wait_ready(),
              "(GET /login did not return the login page)")

        # ---- Phase A: the login wall -------------------------------
        check("A1 unauth / redirects to login",
              curl_status("GET", "/", jar=False) == 303,
              "(no redirect)")
        check("A2 unauth /progress redirects to login",
              curl_status("GET", "/progress", jar=False) == 303)
        body = curl("GET", "/api/status", jar=False, follow=False)
        check("A3 unauth /api/status is 401 JSON",
              json.loads(body).get("error") == "未登录",
              "(body=%r)" % body[:80])
        page = curl("GET", "/login", jar=False)
        check("A4 login page renders",
              'name="username"' in page and 'name="password"' in page
              and "登录" in page)
        check("A5 wrong password stays on login page",
              "账号或密码错误" in curl("POST", "/login", {
                  "username": "admin", "password": "wrong",
                  "next": "/"}, jar=False))

        # ---- Phase B: default login ---------------------------------
        page = curl("POST", "/login", {
            "username": "admin", "password": "admin", "next": "/"})
        check("B1 default admin/admin logs in",
              "修改密码" in page and "退出登录" in page,
              "(settings page not reached)")
        check("B2 authed /api/status is 200",
              curl_status("GET", "/api/status") == 200)

        # ---- Phase C: change password -------------------------------
        page = curl("POST", "/api/password", {
            "current_password": "nope", "new_password": "newpass1",
            "confirm_password": "newpass1"})
        check("C1 wrong current password rejected",
              "当前密码不对" in page)
        page = curl("POST", "/api/password", {
            "current_password": "admin", "new_password": "newpass1",
            "confirm_password": "other"})
        check("C2 mismatched confirmation rejected",
              "两次输入的新密码不一致" in page)
        page = curl("POST", "/api/password", {
            "current_password": "admin", "new_password": "ab",
            "confirm_password": "ab"})
        check("C3 too-short new password rejected",
              "新密码至少" in page)
        page = curl("POST", "/api/password", {
            "current_password": "admin", "new_password": "newpass1",
            "confirm_password": "newpass1"})
        check("C4 password change succeeds", "密码已修改" in page)
        # Old password no longer works (fresh jar, no session).
        fresh_jar = os.path.join(work, "fresh-cookies.txt")
        old_jar, COOKIE_JAR = COOKIE_JAR, fresh_jar
        page = curl("POST", "/login", {
            "username": "admin", "password": "admin", "next": "/"})
        check("C5 old password rejected after change",
              "账号或密码错误" in page)
        page = curl("POST", "/login", {
            "username": "admin", "password": "newpass1", "next": "/"})
        check("C6 new password logs in", "修改密码" in page)
        COOKIE_JAR = old_jar

        # ---- Phase D: logout -----------------------------------------
        page = curl("POST", "/api/logout", {})
        check("D1 logout lands on login page", "登录" in page)
        check("D2 after logout / redirects to login",
              curl_status("GET", "/") == 303)

        # ---- Phase E: /sub stays public ------------------------------
        # Log back in to add a subscription, then fetch it with a
        # fresh jar (no session): it must not redirect to /login.
        curl("POST", "/login", {
            "username": "admin", "password": "newpass1", "next": "/"})
        curl("POST", "/api/subs/add", {
            "name": "demo", "url": "http://127.0.0.1:9/x.yaml"})
        pub_jar = os.path.join(work, "pub-cookies.txt")
        old_jar, COOKIE_JAR = COOKIE_JAR, pub_jar
        status = curl_status("GET", "/sub/demo")
        check("E1 /sub/<name> is public without login",
              status in (200, 404, 502),
              "(status=%s; a 303 would mean a login wall)" % status)
        COOKIE_JAR = old_jar
    finally:
        srv.stop()

    # ---- Phase F: icons ----------------------------------------------
    for path, size in [
        ("ICON.PNG", 64), ("ICON_256.PNG", 256),
        (os.path.join("app", "ui", "images", "icon_64.png"), 64),
        (os.path.join("app", "ui", "images", "icon_256.png"), 256),
    ]:
        info = png_info(os.path.join(ROOT, path))
        check("F %s is %dx%d RGBA PNG" % (path, size, size),
              info == (size, size, 6), "(info=%r)" % (info,))
    # The new design is the globe+bolt artwork, not the old teal disc:
    # the 256 icon is much larger than the old flat placeholder.
    size_256 = os.path.getsize(os.path.join(ROOT, "ICON_256.PNG"))
    check("F new icon artwork present",
          size_256 > 10000, "(ICON_256.PNG is %d bytes)" % size_256)

    print("\n%d passed, %d failed" % (len(PASSES), len(FAILURES)),
          flush=True)
    if FAILURES:
        print("FAILED: %s" % ", ".join(FAILURES), flush=True)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
